export function translate(language: string | undefined, key: string): string {
  const lang = typeof language === 'string' && language in translations ? language : 'English';
  return translations[lang]?.[key] ?? translations.English[key] ?? key;
}

export function localeForLanguage(language: AppLanguage): string {
  switch (language) {
    case 'Filipino': return 'fil-PH';
    case 'Spanish': return 'es-ES';
    case 'French': return 'fr-FR';
    case 'Chinese': return 'zh-CN';
    case 'German': return 'de-DE';
    case 'Japanese': return 'ja-JP';
    case 'Korean': return 'ko-KR';
    case 'Arabic': return 'ar-SA';
    case 'Portuguese': return 'pt-BR';
    case 'Vietnamese': return 'vi-VN';
    case 'Indonesian': return 'id-ID';
    default: return 'en-PH';
  }
}
